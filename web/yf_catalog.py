def market_label(code: str) -> str:
    for m in YF_MARKETS:
        if m["code"] == code:
            return m["name"]
    return code


def translate_name(symbol: str, fallback: str = "") -> str:
    return YF_NAME_ZH.get(symbol) or fallback or symbol


def catalog_items(market: str) -> list[dict[str, Any]]:
    market = (market or "").upper().strip()
    label = market_label(market)
    rows = YF_CATALOG.get(market) or []
    items: list[dict[str, Any]] = []
    for row in rows:
        sym = row["symbol"]
        items.append(
            {
                "symbol": f"yf:{sym}",
                "code": sym,
                "name": translate_name(sym),
                "nameEn": "",
                "market": f"yf:{market}",
                "marketLabel": label,
                "exchange": row.get("exchange") or "YF",
                "category": "yfinance",
                "assetType": "yfinance",
                "source": "yfinance",
            }
        )
    return items
